/**
 * Verifica reglas de cache del hosting y tamaño de assets estáticos en out/.
 * Uso: node scripts/verify-hosting-cache.mjs
 */
import { existsSync, readFileSync, statSync, readdirSync } from 'node:fs';
import { join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const firebaseJsonPath = join(root, 'firebase.json');
const stagingJsonPath = join(root, 'firebase.hosting.staging.json');
const outDir = join(root, 'out');
const nextStaticDir = join(outDir, '_next', 'static');

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
}

function walkSize(dir, acc = { bytes: 0, files: 0 }) {
  if (!existsSync(dir)) return acc;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walkSize(full, acc);
    else {
      acc.bytes += statSync(full).size;
      acc.files += 1;
    }
  }
  return acc;
}

function summarizeByExt(dir) {
  const totals = {};
  if (!existsSync(dir)) return totals;

  function walk(current) {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const full = join(current, entry.name);
      if (entry.isDirectory()) walk(full);
      else {
        const ext = extname(entry.name).toLowerCase() || '(none)';
        totals[ext] = (totals[ext] || 0) + statSync(full).size;
      }
    }
  }

  walk(dir);
  return totals;
}

function assertRule(firebase, source, expectedFragment) {
  const headers = firebase.hosting?.headers ?? [];
  const rule = headers.find((h) => h.source === source);
  const value = rule?.headers?.find((h) => h.key === 'Cache-Control')?.value ?? '';
  const ok = value.includes(expectedFragment);
  return { source, value, ok };
}

function assertStaticBeforeGenericJs(firebase) {
  const headers = firebase.hosting?.headers ?? [];
  const staticIdx = headers.findIndex((h) => h.source === '/_next/static/**');
  const genericIdx = headers.findIndex((h) => h.source === '**/*.@(js|css)');
  const ok = staticIdx >= 0 && genericIdx >= 0 && staticIdx < genericIdx;
  return { ok, staticIdx, genericIdx };
}

// cleanUrls=true serves pages at extensionless paths (/login, /coordinador), so the
// **/*.html rule never matches them and they fall back to a cacheable default. After a
// redeploy that prunes old chunk hashes, stale page HTML 404s its chunks -> server
// returns fallback HTML -> "MIME text/html" script error -> blank screen. The only glob
// that matches a clean URL is **, so its Cache-Control must force revalidation.
function assertCleanUrlHtmlRevalidates(firebase) {
  const headers = firebase.hosting?.headers ?? [];
  const root = headers.find((h) => h.source === '**');
  const value = root?.headers?.find((h) => h.key === 'Cache-Control')?.value ?? '';
  const ok = value.includes('no-store') || value.includes('no-cache');
  return { source: '** (clean URL pages)', value, ok };
}

function main() {
  console.log('\n[verify-hosting-cache] Reporte de optimización de descargas\n');

  if (!existsSync(firebaseJsonPath)) {
    console.error('❌ No existe firebase.json');
    process.exit(1);
  }

  const firebase = JSON.parse(readFileSync(firebaseJsonPath, 'utf8'));
  const checks = [
    assertRule(firebase, '/_next/static/**', 'max-age=31536000'),
    assertRule(firebase, '/_next/static/**', 'immutable'),
    assertRule(firebase, '**/*.html', 'max-age=900'),
    assertRule(firebase, '/sw.js', 'no-cache'),
    assertRule(firebase, '**/*.@(png|jpg|jpeg|svg|webp|gif|ico|avif)', 'max-age=2592000'),
  ];

  let failed = 0;
  for (const check of checks) {
    const mark = check.ok ? '✅' : '❌';
    if (!check.ok) failed += 1;
    console.log(`${mark} ${check.source}`);
    console.log(`   Cache-Control: ${check.value || '(missing)'}\n`);
  }

  const order = assertStaticBeforeGenericJs(firebase);
  if (order.ok) {
    console.log('✅ /_next/static/** appears before **/*.@(js|css)\n');
  } else {
    failed += 1;
    console.log('❌ header order: /_next/static/** must precede **/*.@(js|css)\n');
  }

  // Staging hosting config is generated by prepare-firebase-hosting-staging.mjs.
  // Verify clean-URL pages revalidate there (root cause of the blank-screen bug).
  if (existsSync(stagingJsonPath)) {
    const staging = JSON.parse(readFileSync(stagingJsonPath, 'utf8'));
    const cleanUrl = assertCleanUrlHtmlRevalidates(staging);
    const mark = cleanUrl.ok ? '✅' : '❌';
    if (!cleanUrl.ok) failed += 1;
    console.log(`${mark} [staging] ${cleanUrl.source}`);
    console.log(`   Cache-Control: ${cleanUrl.value || '(missing)'}\n`);
  } else {
    console.log('ℹ️  firebase.hosting.staging.json no encontrado (corre deploy:staging para generarlo).\n');
  }

  if (!existsSync(outDir)) {
    console.warn('⚠️  Carpeta out/ no encontrada. Ejecuta `npm run build` primero.\n');
  } else {
    const staticTotals = walkSize(nextStaticDir);
    const extTotals = summarizeByExt(nextStaticDir);
    console.log('📦 out/_next/static');
    console.log(`   archivos: ${staticTotals.files}`);
    console.log(`   tamaño total: ${formatBytes(staticTotals.bytes)}`);
    const sorted = Object.entries(extTotals).sort((a, b) => b[1] - a[1]).slice(0, 6);
    for (const [ext, size] of sorted) {
      console.log(`   ${ext}: ${formatBytes(size)}`);
    }
    console.log('');
  }

  const swPath = join(root, 'public', 'sw.js');
  if (existsSync(swPath)) {
    const sw = readFileSync(swPath, 'utf8');
    const versionMatch = sw.match(/const CACHE_VERSION = (\d+)/);
    const usesCacheFirst = sw.includes('BYPASS_PREFIXES') && sw.includes('/_next/static/');
    console.log(`🔧 Service Worker: v${versionMatch?.[1] ?? '?'} | bypass _next/static: ${usesCacheFirst ? 'sí' : 'no'}\n`);
  }

  console.log('📋 Checklist manual (DevTools → Network, Disable cache OFF):');
  console.log('   1. Primera visita /login → anotar MB transferidos');
  console.log('   2. Recargar (F5) → _next/static/* debe salir (disk cache) o 0 B');
  console.log('   3. Tras deploy nuevo → solo HTML + chunks con hash nuevo\n');

  if (failed > 0) {
    console.error(`❌ ${failed} regla(s) de cache no cumplen lo esperado.\n`);
    process.exit(1);
  }

  console.log('✅ Reglas de cache verificadas.\n');
}

main();
